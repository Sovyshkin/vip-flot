function buildYachtTourItinerary(tour) {
  if (!Array.isArray(tour.itinerary)) return []
  return tour.itinerary.map((item, index, arr) => {
    let description = 'День строится вокруг перехода, береговой программы и отдыха на борту в комфортном для вашей компании темпе.'
    if (index === 0) {
      description = 'Первый день посвящён выходу на маршрут, знакомству с ритмом путешествия и плавному переходу к основной части тура.'
    } else if (index === arr.length - 1) {
      description = 'Финальный день отводится под обратный переход, завершающие остановки и спокойное возвращение без спешки.'
    } else {
      description = `Основная часть путешествия проходит в формате «${item.title}»: с береговыми точками, временем на прогулки и возможностью подстроить ритм под состав гостей.`
    }
    return {
      ...item,
      description
    }
  })
}

